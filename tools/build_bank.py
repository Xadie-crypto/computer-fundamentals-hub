import json
files = ['systems','apps','programming','networks','trends','laws']
out = {}
counts = {}
for f in files:
    data = json.load(open(f'data/{f}.json', encoding='utf8'))
    qs = data['questions']
    for q in qs:
        q['topic'] = f
    out[f] = qs
    counts[f] = len(qs)
js = "/* Generated by tools/build_bank.py. Do not edit directly. */\nwindow.COMPF_BANK = " + json.dumps(out, ensure_ascii=False, separators=(',',':')) + ";\nwindow.COMPF_COUNTS = " + json.dumps(counts) + ";\n"
open('assets/js/bank.js','w',encoding='utf8',newline='\n').write(js)
print('wrote assets/js/bank.js', len(js), 'bytes')
print(counts, 'total', sum(counts.values()))
